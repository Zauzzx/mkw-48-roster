#!/usr/bin/env python3
"""Compile the payload (the game code patch) with clang for PowerPC into
prebuilt/<variant>/. Only needed when payload/ or addresses/ change: the
roster itself is read from a data file at boot, so adding characters just
needs tools/build.py.

  python3 tools/compile_payload.py [--region RMCE01] [--debug-boot] [--vanilla-select]

Needs clang, ld.lld, llvm-objcopy and llvm-nm with the PowerPC target (any
LLVM 15+; note the official Windows LLVM release leaves PowerPC out).
"""

import argparse
import json
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAYLOAD = ROOT / "payload"
PREBUILT = ROOT / "prebuilt"

CFLAGS = ["--target=powerpc-unknown-eabi", "-mcpu=750", "-O2", "-ffreestanding", "-fno-builtin",
          "-fno-pic", "-fno-common", "-Wall", "-Werror", "-std=c11"]


class BuildError(Exception):
    pass


def load_addresses(region, path=None):
    path = Path(path) if path else ROOT / "addresses" / f"{region}.toml"
    data = tomllib.loads(path.read_text())
    missing = [f"{sec}.{k}" for sec in ("payload", "functions") for k, v in data[sec].items() if v == 0]
    if missing:
        raise BuildError(f"{path.name}: addresses not found yet: {', '.join(missing)}")
    return data


def addresses_h(addr):
    lines = ["#pragma once", "// Generated by tools/build.py. Do not edit.", ""]
    for k, v in addr["functions"].items():
        lines.append(f"#define ADDR_{k} 0x{v:08X}")
    return "\n".join(lines) + "\n"


def run(cmd):
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode:
        raise BuildError(f"{' '.join(map(str, cmd))}\n{res.stderr or res.stdout}")


def tool(name):
    for cand in (name, f"{name}-18", f"{name}-17", f"{name}-16", f"{name}-15"):
        if shutil.which(cand):
            return cand
    raise BuildError(f"{name} not found; install LLVM (clang, lld)")


def compile_payload(addr, build_dir, defines=()):
    gen = build_dir / "gen"
    obj = build_dir / "obj"
    gen.mkdir(parents=True, exist_ok=True)
    obj.mkdir(parents=True, exist_ok=True)
    (gen / "addresses.h").write_text(addresses_h(addr))
    sources = sorted((PAYLOAD / "src").glob("*.[cS]"))
    objects = []
    for src in sources:
        o = obj / (src.name + ".o")
        run([tool("clang"), *CFLAGS, *(f"-D{d}" for d in defines), "-I", PAYLOAD / "include", "-I", gen, "-c", src, "-o", o])
        objects.append(o)
    elf = build_dir / "payload.elf"
    run([tool("ld.lld"), "-T", PAYLOAD / "payload.ld", f"--defsym=PAYLOAD_ADDR=0x{addr['payload']['load_address']:08X}",
         "--gc-sections", "-o", elf, *objects])
    binary = build_dir / "payload.bin"
    run([tool("llvm-objcopy"), "-O", "binary", elf, binary])
    return elf, binary


def symbols(elf):
    out = subprocess.run([tool("llvm-nm"), elf], capture_output=True, text=True, check=True).stdout
    return {parts[2]: int(parts[0], 16) for parts in (l.split() for l in out.splitlines()) if len(parts) == 3}


def variant_name(region, debug_boot, vanilla_select):
    return region + ("-debug" if debug_boot else "") + ("-vanilla-select" if vanilla_select else "")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--region", default="RMCE01")
    ap.add_argument("--addresses", help="use this address file instead of addresses/<region>.toml")
    ap.add_argument("--debug-boot", action="store_true", help="test build: boot straight into character select")
    ap.add_argument("--vanilla-select", action="store_true", help="keep the vanilla select screen (no 48-button layout)")
    ap.add_argument("--build-dir", default=str(ROOT / "out" / "build"))
    args = ap.parse_args(argv)
    variant = variant_name(args.region, args.debug_boot, args.vanilla_select)
    try:
        addr = load_addresses(args.region, args.addresses)
        defines = (["ROSTER_DEBUG_BOOT"] if args.debug_boot else []) + (["ROSTER_VANILLA_SELECT"] if args.vanilla_select else [])
        elf, binary = compile_payload(addr, Path(args.build_dir) / variant, defines)
        syms = symbols(elf)
        limit = addr["payload"].get("max_size")
        used = syms["__bss_end"] - addr["payload"]["load_address"]
        if limit and used > limit:
            raise BuildError(f"payload needs 0x{used:X} bytes but only 0x{limit:X} are reserved")
        dest = PREBUILT / variant
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copy2(binary, dest / "payload.bin")
        info = {
            "region": args.region,
            "load_address": addr["payload"]["load_address"],
            "loader_hook": addr["payload"]["loader_hook"],
            "loader_hook_original": addr["payload"]["loader_hook_original"],
            "symbols": {k: syms[k] for k in ("roster_entry", "roster_replaced_insn", "roster_return")},
            "size": used,
        }
        (dest / "payload.json").write_text(json.dumps(info, indent=2) + "\n")
    except BuildError as e:
        print("error: " + str(e).replace("\n", "\nerror: "), file=sys.stderr)
        return 1
    print(f"Compiled {variant}: 0x{used:X} bytes (with .bss) into {dest}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
