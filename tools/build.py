#!/usr/bin/env python3
"""Build the mod: resolve the roster, generate the payload's data, compile it
with clang for PowerPC and write a Riivolution patch.

  python3 tools/build.py [--region RMCE01] [--out out]

Needs clang, ld.lld and llvm-objcopy (any LLVM 15+). Game files are not
needed for this step.
"""

import argparse
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import roster as roster_mod  # noqa: E402
from ids import IDS, MAX_CHARACTERS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PAYLOAD = ROOT / "payload"
MOD_ID = "mkw-48-roster"

CFLAGS = ["--target=powerpc-unknown-eabi", "-mcpu=750", "-O2", "-ffreestanding", "-fno-builtin",
          "-fno-pic", "-fno-common", "-Wall", "-Werror", "-std=c11"]


class BuildError(Exception):
    pass


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_addresses(region, path=None):
    path = Path(path) if path else ROOT / "addresses" / f"{region}.toml"
    data = tomllib.loads(path.read_text())
    missing = [f"{sec}.{k}" for sec in ("payload", "functions") for k, v in data[sec].items() if not v]
    if missing:
        raise BuildError(f"{path.name}: addresses not found yet: {', '.join(missing)}")
    return data


def addresses_h(addr):
    lines = ["#pragma once", "// Generated by tools/build.py. Do not edit.", ""]
    for k, v in addr["functions"].items():
        lines.append(f"#define ADDR_{k} 0x{v:08X}")
    return "\n".join(lines) + "\n"


def roster_table_c(entries):
    by_id = {e.id: e for e in entries}
    rows = []
    for cid, vanilla, _, suffix in IDS:
        e = by_id.get(cid)
        if e:
            rows.append(f"    [0x{cid:02X}] = {{{c_string(e.name)}, {c_string(e.suffix)}, 0x{e.stats_from:02X}, {int(e.custom)}}},")
        else:
            # Unused extra ID: point it at Mario so nothing reads a null string.
            rows.append(f"    [0x{cid:02X}] = {{\"Mario\", \"mr\", 0x00, 0}}, // unused ({vanilla})")
    order = ", ".join(f"0x{e.id:02X}" for e in entries)
    return "\n".join([
        "// Generated by tools/build.py from characters/ and roster.toml. Do not edit.",
        '#include "roster_table.h"',
        "",
        f"const u32 rosterCount = {len(entries)};",
        f"const u8 rosterButtonToId[ROSTER_MAX] = {{{order}}};",
        "const struct RosterCharacter rosterById[ROSTER_MAX] = {",
        *rows,
        "};",
        "",
    ])


def run(cmd):
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode:
        raise BuildError(f"{' '.join(map(str, cmd))}\n{res.stderr or res.stdout}")


def tool(name):
    for cand in (name, f"{name}-18", f"{name}-17", f"{name}-16", f"{name}-15"):
        if shutil.which(cand):
            return cand
    raise BuildError(f"{name} not found; install LLVM (clang, lld)")


def compile_payload(addr, entries, build_dir):
    gen = build_dir / "gen"
    obj = build_dir / "obj"
    gen.mkdir(parents=True, exist_ok=True)
    obj.mkdir(parents=True, exist_ok=True)
    (gen / "addresses.h").write_text(addresses_h(addr))
    (gen / "roster_table.c").write_text(roster_table_c(entries))
    sources = sorted((PAYLOAD / "src").glob("*.[cS]")) + [gen / "roster_table.c"]
    objects = []
    for src in sources:
        o = obj / (src.name + ".o")
        run([tool("clang"), *CFLAGS, "-I", PAYLOAD / "include", "-I", gen, "-c", src, "-o", o])
        objects.append(o)
    elf = build_dir / "payload.elf"
    run([tool("ld.lld"), "-T", PAYLOAD / "payload.ld", f"--defsym=PAYLOAD_ADDR=0x{addr['payload']['load_address']:08X}",
         "--gc-sections", "-o", elf, *objects])
    binary = build_dir / "payload.bin"
    run([tool("llvm-objcopy"), "-O", "binary", elf, binary])
    return elf, binary


def symbols(elf):
    out = subprocess.run([tool("llvm-nm"), elf], capture_output=True, text=True, check=True).stdout
    return {parts[2]: int(parts[0], 16) for parts in (l.split() for l in out.splitlines()) if len(parts) == 3}


def branch(src, dst):
    return 0x48000000 | ((dst - src) & 0x03FFFFFC)


def riivolution_xml(region, addr, syms, original_insn):
    hook = addr["payload"]["loader_hook"]
    base = addr["payload"]["load_address"]
    return f"""<wiidisc version="1">
\t<id game="{region[:4]}" />
\t<options>
\t\t<section name="48 Roster">
\t\t\t<option name="48 Roster">
\t\t\t\t<choice name="Enabled"><patch id="roster48" /></choice>
\t\t\t</option>
\t\t</section>
\t</options>
\t<patch id="roster48">
\t\t<memory offset="0x{base:08X}" valuefile="/{MOD_ID}/code/payload-{region}.bin" />
\t\t<memory offset="0x{syms['roster_replaced_insn']:08X}" value="{original_insn:08X}" />
\t\t<memory offset="0x{syms['roster_return']:08X}" value="{branch(syms['roster_return'], hook + 4):08X}" />
\t\t<memory offset="0x{hook:08X}" value="{branch(hook, syms['roster_entry']):08X}" original="{original_insn:08X}" />
\t\t<folder external="/{MOD_ID}/files" disc="/" create="true" recursive="true" />
\t</patch>
</wiidisc>
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--region", default="RMCE01")
    ap.add_argument("--addresses", help="use this address file instead of addresses/<region>.toml")
    ap.add_argument("--out", default=str(ROOT / "out"))
    args = ap.parse_args(argv)
    try:
        entries = roster_mod.resolve(roster_mod.load_characters(), roster_mod.load_order())
        addr = load_addresses(args.region, args.addresses)
        if "loader_hook_original" not in addr["payload"]:
            raise BuildError("address file needs payload.loader_hook_original (the instruction the loader hook overwrites)")
        out = Path(args.out)
        elf, binary = compile_payload(addr, entries, out / "build" / args.region)
        syms = symbols(elf)
        code = out / MOD_ID / "code"
        code.mkdir(parents=True, exist_ok=True)
        shutil.copy2(binary, code / f"payload-{args.region}.bin")
        riiv = out / "riivolution"
        riiv.mkdir(parents=True, exist_ok=True)
        (riiv / f"{MOD_ID}.xml").write_text(riivolution_xml(args.region, addr, syms, addr["payload"]["loader_hook_original"]))
    except (roster_mod.RosterError, BuildError) as e:
        print("error: " + str(e).replace("\n", "\nerror: "), file=sys.stderr)
        return 1
    print(f"Built {len(entries)}/{MAX_CHARACTERS} characters, payload {binary.stat().st_size} bytes, into {out}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
